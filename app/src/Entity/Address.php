<?php

namespace App\Entity;

use App\Repository\AddressRepository;
use Doctrine\ORM\Mapping as ORM;

#[ORM\Entity(repositoryClass: AddressRepository::class)]
class Address
{
    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column]
    private int $id;

    #[ORM\Column]
    private int $number;

    #[ORM\Column(length: 255)]
    private string $street;

    #[ORM\Column(name: 'zipCode', length: 10)]
    private string $zipCode;

    #[ORM\Column(name: 'addressInfo', length: 255, nullable: true)]
    private ?string $addressInfo = null;

    #[ORM\Column(length: 255)]
    private string $city;

    #[ORM\Column(length: 255, nullable: true)]
    private ?string $country = null;

    public function getId(): int
    {
        return $this->id;
    }

    public function getNumber(): int
    {
        return $this->number;
    }

    public function setNumber(int $number): static
    {
        $this->number = $number;

        return $this;
    }

    public function getStreet(): string
    {
        return $this->street;
    }

    public function setStreet(string $street): static
    {
        $this->street = $street;

        return $this;
    }

    public function getZipCode(): string
    {
        return $this->zipCode;
    }

    public function setZipCode(string $zipCode): static
    {
        $this->zipCode = $zipCode;

        return $this;
    }

    public function getAddressInfo(): ?string
    {
        return $this->addressInfo;
    }

    public function setAddressInfo(?string $addressInfo): static
    {
        $this->addressInfo = $addressInfo;

        return $this;
    }

    public function getCity(): string
    {
        return $this->city;
    }

    public function setCity(string $city): static
    {
        $this->city = $city;

        return $this;
    }

    public function getCountry(): ?string
    {
        return $this->country;
    }

    public function setCountry(?string $country): static
    {
        $this->country = $country;

        return $this;
    }
}
